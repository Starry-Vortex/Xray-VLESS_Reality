# 创建快捷指令
create_shortcut() {
  cat > "$work_dir/r.sh" << EOF
#!/usr/bin/env bash

bash <(curl -Ls https://raw.githubusercontent.com/eooce/sing-box/main/sing-box.sh) \$1
EOF
  chmod +x "$work_dir/sb.sh"
  ln -sf "$work_dir/sb.sh" /usr/bin/sb
  if [ -s /usr/bin/sb ]; then
    green "\n快捷指令 r 创建成功\n"
  else
    red "\n快捷指令创建失败\n"
  fi
}

